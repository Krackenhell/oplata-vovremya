// Шаблоны документов: письмо-напоминание (резерв, если нет ответа LLM) и досудебная претензия.
// Претензия собирается шаблоном, а не генеративной моделью: юридический текст должен быть точным.
import { rub, dateRu, diffDays, addDays } from './util.js';

// Ключевая ставка Банка России. Значение 14% действует с 27.07.2026 (решение 23.10.2026 — сохранить).
// Таблица настраиваемая: при изменении ставки добавьте строку.
export const KEY_RATE = [{ from: '2026-07-27', rate: 0.14 }];

export function interest395(sum, from, to, table = KEY_RATE) {
  if (!(sum > 0) || to <= from) return { total: 0, parts: [] };
  const parts = [];
  const sorted = [...table].sort((a, b) => a.from.localeCompare(b.from));
  let cur = from;
  while (cur < to) {
    const row = [...sorted].reverse().find(r => r.from <= cur) || sorted[0];
    const next = sorted.find(r => r.from > cur);
    const end = next && next.from < to ? next.from : to;
    const d = diffDays(end, cur);
    const year = Number(cur.slice(0, 4)), base = (year % 4 === 0 && (year % 100 !== 0 || year % 400 === 0)) ? 366 : 365;
    parts.push({ from: cur, to: end, days: d, rate: row.rate, amount: sum * row.rate * d / base });
    cur = end;
  }
  return { total: parts.reduce((s, p) => s + p.amount, 0), parts };
}

export function letterTemplate(a, supplier) {
  const i = a.inv, name = (a.client.contact || '').split(',')[0];
  const hello = `Добрый день${name ? ', ' + name.split(' ')[0] : ''}!`;
  const ref = `по счёту № ${i.id} от ${dateRu(i.issued)} остаётся к оплате ${rub(a.bal)} (срок по договору — ${dateRu(i.due)}).`;
  const body = {
    documents: `Напоминаем, что ${ref} Вы писали, что для оплаты нужен корректный закрывающий документ. Подготовим его сегодня и направим через ЭДО. Подскажите, пожалуйста, всё ли ещё нужно для проведения платежа и на какую дату его можно планировать?`,
    dispute: `Напоминаем, что ${ref} Мы видим ваши замечания и хотим быстро их снять. Предлагаем созвон в удобное для вас время, чтобы сверить объём с договором. Если часть суммы не вызывает вопросов, будем благодарны за её оплату до решения спорной части.`,
    liquidity: `Напоминаем, что ${ref} Понимаем, что сейчас непростой период. Предлагаем зафиксировать реалистичный график: сумму и дату первого платежа. Так мы сможем сохранить работу по текущему проекту.`,
    approval: `Напоминаем, что ${ref} Спасибо, что держите нас в курсе согласования. Подтвердите, пожалуйста, дату, на которую платёж поставлен в реестр, — мы сверим поступление.`,
    details: `Напоминаем, что ${ref} Направляем актуальные реквизиты письмом за подписью и платёжную ссылку — с ней не нужно перебивать реквизиты вручную. Извините за неудобство.`,
    silence: `Напоминаем, что ${ref} ${a.brokenPromise ? 'Ранее вы планировали оплату на ' + dateRu(a.promised) + ', но платёж пока не поступил. ' : ''}Подскажите, пожалуйста, всё ли в порядке с документами и когда ожидать оплату?`,
    paid: `Спасибо за оплату. Мы сверяем поступление по счёту № ${i.id} с выпиской и закроем его в реестре. Если платёж прошёл одной суммой по нескольким счетам, пришлите, пожалуйста, номер платёжного поручения.`,
  }[a.cause] || `Напоминаем, что ${ref} Подскажите, пожалуйста, статус оплаты.`;
  return { subject: `Счёт № ${i.id}: ${a.cause === 'paid' ? 'сверка оплаты' : 'статус оплаты'}`, body: `${hello}\n\n${body}\n\nС уважением,\n${supplier.name}` };
}

export function claimText(a, supplier, today) {
  const i = a.inv, from = addDays(i.due, 1);
  const pr = interest395(a.bal, from, today);
  const deadline = addDays(today, 30);
  return `ПРЕТЕНЗИЯ
об оплате задолженности по счёту № ${i.id}

От: ${supplier.name}, ИНН ${supplier.inn}
Кому: ${a.client.name}, ИНН ${i.inn}

${supplier.name} выполнило работы (оказало услуги) по счёту № ${i.id} от ${dateRu(i.issued)} на сумму ${rub(i.amount)}. Срок оплаты наступил ${dateRu(i.due)}. На ${dateRu(today)} оплачено ${rub(i.paid || 0)}, задолженность составляет ${rub(a.bal)}.

На основании статей 309, 310 и 395 Гражданского кодекса РФ просим в срок до ${dateRu(deadline)} оплатить:
— основной долг: ${rub(a.bal)};
— проценты за пользование чужими денежными средствами за период с ${dateRu(from)} по ${dateRu(today)} (${pr.parts.reduce((s, p) => s + p.days, 0)} дн., ключевая ставка ${pr.parts.map(p => (p.rate * 100).toFixed(2).replace('.', ',') + '%').join(', ')}): ${rub(pr.total)}.

Если договором предусмотрена неустойка, вместо процентов по ст. 395 ГК РФ применяется неустойка по договору — проверьте условия перед отправкой.

В случае неоплаты в указанный срок мы будем вынуждены обратиться в арбитражный суд (претензионный порядок — ч. 5 ст. 4 АПК РФ). Это повлечёт дополнительные расходы на государственную пошлину и судебные издержки.

Реквизиты для оплаты прилагаются.

____________________ / ____________________
Генеральный директор ${supplier.name}

Черновик подготовлен сервисом «Оплата вовремя». Проверьте сумму, условия договора и подпись перед отправкой.`;
}
