// Резервный разбор переписки правилами: работает в браузере без сети и без ключей.
// Используется для загруженных пользователем данных и как базовая линия для сравнения с Jev
// (раздел «Качество разбора»). Последнее сообщение клиента важнее ранних: причины меняются.

const NEG = /(?:нет|без|не)\s+(?:вопросов|претензий|замечаний|проблем)|дело не в (?:этом|деньгах)|деньги есть|в порядке|всё ок|все ок|приняты|получили, вопросов/i;

export const RULES = {
  paid: [
    /оплат(?:или|ил[аи]?|у провели)|(?:деньги|платёж|платеж) (?:ушл|отправ|прош)|п\/п\s*№?\s*\d|платёжк|платежк|рассчитал|взаимозач|списание подтвержд|провели (?:вчера|платёж|оплату)|уже заплатил|счёт закрыт|счет закрыт|оплатил[аи]? (?:наша|за нас)/i,
  ],
  details: [
    /реквизит|расч[её]тн[а-яё]* сч[её]т|бик(?![а-яё])|корсч|кпп получател|сч[её]т получателя|вернул[а-яё]* (?:банк|обратно|платёж|платеж)|платёж вернулся|платеж вернулся|деньги вернул|не пропуска[а-яё]* платёж|не пропуска[а-яё]* платеж|старое наименование/i,
  ],
  documents: [
    /акт(?![а-яё])|акта(?![а-яё])|акт[аеуом]?\s|упд|сч[её]т[а-я]*[- ]фактур|накладн|закрывающ[а-яё]* документ|документ[а-яё]* о при[её]мке|форм[а-яё]* при[её]мки|оригинал|диадок|эдо(?![а-яё])|подписанн[а-яё]* с вашей|без подписи|по форме|инвойс/i,
  ],
  dispute: [
    /не соглас|расхожд|уточните сумму|исправленн[а-яё]* сч[её]т|по договору(?![а-яё]).{0,40}стоимост|замечани|не устраива|качеств|не принят|не можем принять|удержива|удержим|неустойк|скидк|акт сверки|выставил[а-яё]* за|объ[её]м[а-яё]* (?:работ|услуг)|спор/i,
  ],
  liquidity: [
    /кассов[а-яё]* разрыв|нет (?:сейчас )?(?:денег|средств)|денег (?:сейчас )?нет|нехватк|финансов[а-яё]* трудност|ликвидност|туго с деньгами|арестован|блокировк|овердрафт|кредитн[а-яё]* лини|платим только|не заплатили за|реструктуриз|задерживает нам деньги|отсутстви[а-яё]* (?:денежных )?средств|сложн[а-яё]* (?:финансов[а-яё]* )?ситуаци|платежеспособ/i,
  ],
  approval: [
    /согласован|на подписи|у директора|казначейств|реестр[а-яё]* (?:на|платеж)|платёжн[а-яё]* календар|платежн[а-яё]* календар|по (?:средам|четвергам|пятницам|вторникам)|визу|утвержд|одобрени|головн[а-яё]* офис|служб[а-яё]* безопасност|собственник/i,
  ],
};
const ORDER = ['paid', 'details', 'liquidity', 'dispute', 'documents', 'approval'];

function sentences(text) {
  return String(text || '').split(/(?<=[.!?…])\s+|\n+/).map(s => s.trim()).filter(Boolean);
}

export function classifyText(text) {
  const hits = {};
  for (const s of sentences(text)) {
    for (const k of ORDER) {
      if (!RULES[k].some(re => re.test(s))) continue;
      // «Акт получили, вопросов нет» — упоминание документа без проблемы
      if ((k === 'documents' || k === 'liquidity' || k === 'dispute') && NEG.test(s) && !/но |однако|пока не/i.test(s)) continue;
      (hits[k] ||= []).push(s);
    }
  }
  const found = ORDER.filter(k => hits[k]);
  return { cause: found[0] || 'silence', found, evidence: found.length ? hits[found[0]][0] : '' };
}

export function analyzeRules(inv) {
  const client = (inv.messages || []).map((m, i) => ({ ...m, i })).filter(m => m.from === 'client');
  for (let j = client.length - 1; j >= 0; j--) {
    const r = classifyText(client[j].text);
    if (r.found.length) return { ...r, messageIndex: client[j].i, source: 'rules' };
  }
  const last = client[client.length - 1];
  return { cause: 'silence', found: [], evidence: '', messageIndex: last ? last.i : -1, source: 'rules' };
}

const MONTHS = { январ: 1, феврал: 2, март: 3, апрел: 4, ма: 5, июн: 6, июл: 7, август: 8, сентябр: 9, октябр: 10, ноябр: 11, декабр: 12 };

// Дата обещанной оплаты: «Остаток оплатим 15.10.2026», «попадёт в реестр 30.10.2026», «перечислим 5 ноября».
// Дата берётся только из предложения с глаголом будущей оплаты и не раньше даты самого письма:
// «платёж от 18 октября вернулся» — не обещание.
const FUTURE_PAY = /оплатим|перечислим|переведём|переведем|заплатим|поставим (?:оплату|в реестр|платёж)|попад[её]т в реестр|в реестр[ау]? на|оплата будет|планируем оплат|ориентируем|рассчитаемся/i;
export function promiseDate(text, msgDate = '0000-00-00', year = Number(String(msgDate).slice(0, 4)) || 2026) {
  for (const s of sentences(text)) {
    if (!FUTURE_PAY.test(s)) continue;
    let d = null, m = /(\d{2})\.(\d{2})\.(\d{4})/.exec(s);
    if (m) d = `${m[3]}-${m[2]}-${m[1]}`;
    else if ((m = /(?:^|[^\d])(\d{1,2})\s+(январ|феврал|март|апрел|ма|июн|июл|август|сентябр|октябр|ноябр|декабр)[а-яё]*/i.exec(s))) {
      d = `${year}-${String(MONTHS[m[2].toLowerCase()]).padStart(2, '0')}-${m[1].padStart(2, '0')}`;
    }
    if (d && d >= msgDate) return d;
  }
  return null;
}
